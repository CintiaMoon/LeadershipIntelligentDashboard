package com.company.leadershipintelligence.service.command;

import com.company.leadershipintelligence.domain.enums.QuestionType;
import com.company.leadershipintelligence.domain.model.ScopedResponse;
import com.company.leadershipintelligence.domain.model.ScoringInput;
import com.company.leadershipintelligence.domain.valueobject.OrganizationId;
import com.company.leadershipintelligence.domain.valueobject.TenantId;

import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.UUID;

/**
 * An assessment and its answers submitted for scoring (decisions D13, D14, D45). The tenant comes from the security
 * context and the organization has already been checked against the caller's organizations by the API layer.
 * The assessment id is generated by the server. A request carries either one answer per question ({@code inputs}, the
 * earlier form) or answers with a scope ({@code responses}); {@code responses} is empty for the earlier form.
 */
public record CalculateCommand(
        TenantId tenantId,
        OrganizationId organizationId,
        String templateId,
        int templateVersion,
        String status,
        Instant completedAt,
        List<ScoringInput> inputs,
        String idempotencyKey,
        Map<String, QuestionType> declaredTypes,
        List<ScopedResponse> responses,
        UUID explicitConfigurationVersionId) {

    public CalculateCommand(TenantId tenantId, OrganizationId organizationId, String templateId, int templateVersion,
                            String status, Instant completedAt, List<ScoringInput> inputs, String idempotencyKey,
                            Map<String, QuestionType> declaredTypes, List<ScopedResponse> responses) {
        this(tenantId, organizationId, templateId, templateVersion, status, completedAt, inputs, idempotencyKey, declaredTypes, responses, null);
    }

    public CalculateCommand(TenantId tenantId, OrganizationId organizationId, String templateId, int templateVersion,
                            String status, Instant completedAt, List<ScoringInput> inputs, String idempotencyKey,
                            Map<String, QuestionType> declaredTypes) {
        this(tenantId, organizationId, templateId, templateVersion, status, completedAt, inputs, idempotencyKey, declaredTypes, List.of(), null);
    }

    public CalculateCommand(TenantId tenantId, OrganizationId organizationId, String templateId, int templateVersion,
                            String status, Instant completedAt, List<ScoringInput> inputs, String idempotencyKey) {
        this(tenantId, organizationId, templateId, templateVersion, status, completedAt, inputs, idempotencyKey, Map.of(), List.of(), null);
    }

    /** {@code declaredTypes} are question types a client stated for compatibility; they are only checked, never trusted. */
    public CalculateCommand {
        inputs = List.copyOf(inputs);
        declaredTypes = Map.copyOf(declaredTypes);
        responses = List.copyOf(responses);
        if (!inputs.isEmpty() && !responses.isEmpty()) {
            throw new IllegalArgumentException("a command carries inputs or responses, not both");
        }
    }

    /** Every answer with its scope; earlier-form inputs are organization answers. */
    public List<ScopedResponse> scopedResponses() {
        return responses.isEmpty()
                ? inputs.stream().map(i -> ScopedResponse.organization(i.questionId(), i.answer())).toList()
                : responses;
    }
}
